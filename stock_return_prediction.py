# COMMAND 1: IMPORT LIBRARIES
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Ridge, Lasso
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score


# COMMAND 2: LOAD DATASET
FILE_NAME = "RELIANCE.NS_1973-05-08_2025-03-01.csv"
df = pd.read_csv(FILE_NAME)

print("\n" + "=" * 70)
print("DATASET LOADED SUCCESSFULLY")
print("=" * 70)


# COMMAND 3: BASIC DATASET INFORMATION
print("\nDataset Shape:")
print("Rows:", df.shape[0])
print("Columns:", df.shape[1])

print("\nColumn Names:")
print(df.columns.tolist())

print("\nFirst 5 Records:")
print(df.head())

print("\nDataset Information:")
df.info()


# COMMAND 4: MISSING VALUES
print("\nMISSING VALUES")
print(df.isnull().sum())


# COMMAND 5: DUPLICATES
print("\nDUPLICATE ROWS:", df.duplicated().sum())


# COMMAND 6: DATE CONVERSION
df["date"] = pd.to_datetime(df["date"], errors="coerce")

print("\nDATE RANGE")
print("Start:", df["date"].min())
print("End  :", df["date"].max())


# COMMAND 7: STATISTICAL SUMMARY
print("\nSTATISTICAL SUMMARY")
print(df.describe())


# COMMAND 8: CREATE DAILY RETURN
# Return = percentage change in closing price
df["Return"] = df["close"].pct_change()

print("\nFIRST 10 RETURNS")
print(df[["date", "close", "Return"]].head(10))

# Remove first NaN return
df = df.dropna(subset=["Return"])


# COMMAND 9: CUMULATIVE RETURN
df["Cumulative_Return"] = (1 + df["Return"]).cumprod() - 1


# COMMAND 10: CLOSING PRICE GRAPH
plt.figure(figsize=(12, 6))
plt.plot(df["date"], df["close"])
plt.title("Reliance Industries Closing Price Trend")
plt.xlabel("Date")
plt.ylabel("Closing Price")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()


# COMMAND 11: OHLC GRAPH
plt.figure(figsize=(12, 6))
plt.plot(df["date"], df["open"], label="Open")
plt.plot(df["date"], df["high"], label="High")
plt.plot(df["date"], df["low"], label="Low")
plt.plot(df["date"], df["close"], label="Close")
plt.title("Reliance Stock OHLC Price Trend")
plt.xlabel("Date")
plt.ylabel("Price")
plt.legend()
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()


# COMMAND 12: VOLUME GRAPH
plt.figure(figsize=(12, 5))
plt.plot(df["date"], df["volume"])
plt.title("Trading Volume Over Time")
plt.xlabel("Date")
plt.ylabel("Volume")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()


# COMMAND 13: RETURN DISTRIBUTION
plt.figure(figsize=(10, 5))
sns.histplot(df["Return"], bins=50, kde=True)
plt.title("Distribution of Daily Stock Returns")
plt.xlabel("Daily Return")
plt.ylabel("Frequency")
plt.tight_layout()
plt.show()


# COMMAND 14: RETURN BOXPLOT
plt.figure(figsize=(8, 5))
sns.boxplot(x=df["Return"])
plt.title("Boxplot of Daily Stock Returns")
plt.xlabel("Daily Return")
plt.tight_layout()
plt.show()


# COMMAND 15: CORRELATION MATRIX
features_for_correlation = [
    "open", "high", "low", "close", "adj_close", "volume", "Return"
]

correlation = df[features_for_correlation].corr()

print("\nCORRELATION MATRIX")
print(correlation)


# COMMAND 16: CORRELATION HEATMAP
plt.figure(figsize=(10, 7))
sns.heatmap(correlation, annot=True, cmap="coolwarm", fmt=".2f")
plt.title("Correlation Heatmap")
plt.tight_layout()
plt.show()


# COMMAND 17: RETURN OVER TIME
plt.figure(figsize=(12, 5))
plt.plot(df["date"], df["Return"])
plt.title("Daily Stock Return Over Time")
plt.xlabel("Date")
plt.ylabel("Return")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()


# COMMAND 18: CUMULATIVE RETURN GRAPH
plt.figure(figsize=(12, 5))
plt.plot(df["date"], df["Cumulative_Return"])
plt.title("Cumulative Stock Return")
plt.xlabel("Date")
plt.ylabel("Cumulative Return")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()


# COMMAND 19: OUTLIER ANALYSIS
Q1 = df["Return"].quantile(0.25)
Q3 = df["Return"].quantile(0.75)
IQR = Q3 - Q1

lower_limit = Q1 - 1.5 * IQR
upper_limit = Q3 + 1.5 * IQR

outliers = df[
    (df["Return"] < lower_limit) |
    (df["Return"] > upper_limit)
]

print("\nOUTLIER ANALYSIS")
print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Lower Limit:", lower_limit)
print("Upper Limit:", upper_limit)
print("Number of Return Outliers:", len(outliers))


# COMMAND 20: SELECT ML FEATURES AND TARGET
# X = input features
# y = target
ml_features = [
    "open", "high", "low", "close", "adj_close", "volume"
]

X = df[ml_features]
y = df["Return"]

print("\nML INPUT FEATURES:")
print(ml_features)
print("TARGET: Return")


# COMMAND 21: TRAIN-TEST SPLIT
# 80% training, 20% testing
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42
)

print("\nTRAINING RECORDS:", len(X_train))
print("TESTING RECORDS :", len(X_test))


# COMMAND 22: FEATURE SCALING
# Fit only on training data to avoid data leakage.
scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

print("\nFEATURE SCALING COMPLETED")


# COMMAND 23: RIDGE REGRESSION
# Ridge = L2 regularization
ridge_model = Ridge(alpha=1.0)
ridge_model.fit(X_train_scaled, y_train)
ridge_prediction = ridge_model.predict(X_test_scaled)

print("RIDGE REGRESSION COMPLETED")


# COMMAND 24: LASSO REGRESSION
# Lasso = L1 regularization
lasso_model = Lasso(alpha=0.001)
lasso_model.fit(X_train_scaled, y_train)
lasso_prediction = lasso_model.predict(X_test_scaled)

print("LASSO REGRESSION COMPLETED")


# COMMAND 25: EVALUATION FUNCTION
def evaluate_model(name, actual, predicted):
    mse = mean_squared_error(actual, predicted)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(actual, predicted)
    r2 = r2_score(actual, predicted)

    print("\n" + "=" * 60)
    print(name)
    print("=" * 60)
    print("MSE :", mse)
    print("RMSE:", rmse)
    print("MAE :", mae)
    print("R2  :", r2)

    return mse, rmse, mae, r2


# COMMAND 26: RIDGE EVALUATION
ridge_results = evaluate_model(
    "RIDGE REGRESSION RESULTS",
    y_test,
    ridge_prediction
)


# COMMAND 27: LASSO EVALUATION
lasso_results = evaluate_model(
    "LASSO REGRESSION RESULTS",
    y_test,
    lasso_prediction
)


# COMMAND 28: MODEL COMPARISON
results = pd.DataFrame({
    "Model": ["Ridge", "Lasso"],
    "MSE": [ridge_results[0], lasso_results[0]],
    "RMSE": [ridge_results[1], lasso_results[1]],
    "MAE": [ridge_results[2], lasso_results[2]],
    "R2": [ridge_results[3], lasso_results[3]]
})

print("\nMODEL COMPARISON")
print(results)


# COMMAND 29: COEFFICIENT COMPARISON
coefficient_table = pd.DataFrame({
    "Feature": ml_features,
    "Ridge_Coefficient": ridge_model.coef_,
    "Lasso_Coefficient": lasso_model.coef_
})

print("\nMODEL COEFFICIENTS")
print(coefficient_table)


# COMMAND 30: RIDGE ACTUAL VS PREDICTED
plt.figure(figsize=(12, 5))
plt.plot(y_test.values[:200], label="Actual Return")
plt.plot(ridge_prediction[:200], label="Ridge Predicted Return")
plt.title("Ridge: Actual vs Predicted Return")
plt.xlabel("Test Sample")
plt.ylabel("Return")
plt.legend()
plt.tight_layout()
plt.show()


# COMMAND 31: LASSO ACTUAL VS PREDICTED
plt.figure(figsize=(12, 5))
plt.plot(y_test.values[:200], label="Actual Return")
plt.plot(lasso_prediction[:200], label="Lasso Predicted Return")
plt.title("Lasso: Actual vs Predicted Return")
plt.xlabel("Test Sample")
plt.ylabel("Return")
plt.legend()
plt.tight_layout()
plt.show()


# COMMAND 32: SAVE RESULTS
results.to_csv("model_results.csv", index=False)
coefficient_table.to_csv("model_coefficients.csv", index=False)

print("\nRESULT FILES CREATED:")
print("model_results.csv")
print("model_coefficients.csv")


